    SUM(oi.quantity * oi.unit_price) AS revenue
FROM sellers s
JOIN products p
    ON p.seller_id = s.id
JOIN order_items oi
    ON oi.product_id = p.id
GROUP BY s.id, s.company_name
HAVING SUM(oi.quantity * oi.unit_price) > 0
ORDER BY revenue DESC;
