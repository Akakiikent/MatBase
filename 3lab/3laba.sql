DO $fix$
DECLARE
    address_type TEXT;
    user_type TEXT;
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'orders'
          AND column_name = 'address_id'
    )
    AND to_regclass('addresses') IS NULL
    THEN
        SELECT format_type(a.atttypid, a.atttypmod)
        INTO address_type
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema()
          AND c.relname = 'orders'
          AND a.attname = 'address_id'
          AND a.attnum > 0
          AND NOT a.attisdropped;

        SELECT format_type(a.atttypid, a.atttypmod)
        INTO user_type
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema()
          AND c.relname = 'users'
          AND a.attname = 'id'
          AND a.attnum > 0
          AND NOT a.attisdropped;

        IF address_type IN ('smallint', 'integer', 'bigint')
           AND user_type IS NOT NULL
        THEN
            EXECUTE format(
                'CREATE TABLE %I.addresses (
                    id %s GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id %s,
                    city TEXT,
                    street TEXT,
                    house TEXT
                )',
                current_schema(),
                address_type,
                user_type
            );
        ELSE
            RAISE EXCEPTION
                'Проверь типы orders.address_id и users.id';
        END IF;
    END IF;
END;
$fix$;


