WITH RECURSIVE subtree AS (
    SELECT id, parent_id, name, 1 AS level
    FROM categories
    WHERE name = 'Книги'
    UNION ALL
    SELECT c.id, c.parent_id, c.name, st.level + 1
    FROM categories AS c
    JOIN subtree AS st ON c.parent_id = st.id
)
SELECT id, parent_id, name, level
FROM subtree
ORDER BY level, id;
